export default function EmojiPicker({
  onPick,
  onClose,
}: {
  onPick: (emoji: string) => void;
  onClose: () => void;
}) {
  const [category, setCategory] = useState(CATEGORIES[0].id);
  const [query, setQuery] = useState('');
  const rootRef = useRef<HTMLDivElement>(null);
  const active = CATEGORIES.find((c) => c.id === category) || CATEGORIES[0];

  const results = useMemo(() => {
    const q = query.trim().toLowerCase();
    if (!q) return active.emojis;
    const fromCats = CATEGORIES.filter(
      (c) => c.label.toLowerCase().includes(q) || c.id.toLowerCase().includes(q),
    );
    if (fromCats.length > 0) return fromCats.flatMap((c) => c.emojis);
    return [];
  }, [active.emojis, query]);

  useEffect(() => {
    const onDoc = (e: MouseEvent) => {
      if (!rootRef.current?.contains(e.target as Node)) onClose();
    };
    const onKey = (e: KeyboardEvent) => {
      if (e.key === 'Escape') onClose();
    };
    document.addEventListener('mousedown', onDoc);
    document.addEventListener('keydown', onKey);
    return () => {
      document.removeEventListener('mousedown', onDoc);
      document.removeEventListener('keydown', onKey);
    };
  }, [onClose]);

  return (
    <div
      ref={rootRef}
      className="rounded-3xl border border-border bg-card shadow-xl overflow-hidden"
    >
      <div className="px-3 pt-3">
        <input
          value={query}
          onChange={(e) => setQuery(e.target.value)}
          placeholder="Search smileys, food, flags…"
          className="w-full px-3 py-2 rounded-2xl border border-border bg-background text-sm focus:outline-none focus:ring-2 focus:ring-ring"
        />
      </div>
      {!query && (
        <div className="flex gap-0.5 px-2 pt-2 overflow-x-auto border-b border-border">
          {CATEGORIES.map((c) => (
            <button
              key={c.id}
              type="button"
              title={c.label}
              aria-label={c.label}
              onClick={() => setCategory(c.id)}
              className={`w-9 h-9 rounded-xl text-lg shrink-0 flex items-center justify-center ${
                category === c.id ? 'bg-primary/15' : 'hover:bg-muted'
              }`}
              style={{ fontFamily: EMOJI_FONT }}
            >
              {c.icon}
            </button>
          ))}
        </div>
      )}
      <div className="p-2 grid grid-cols-8 sm:grid-cols-9 gap-0.5 max-h-64 overflow-y-auto">
        {results.length === 0 && (
          <p className="col-span-full text-sm text-muted-foreground px-2 py-6 text-center">
            No matches. Try smileys, food, travel, or flags.
          </p>
        )}
        {results.map((emo, i) => (
          <button
            key={`${emo}-${i}`}
            type="button"
            onClick={() => onPick(emo)}
            className="h-9 rounded-xl hover:bg-muted text-[22px] leading-none flex items-center justify-center"
            style={{ fontFamily: EMOJI_FONT }}
            aria-label={`Insert ${emo}`}
          >
            {emo}
          </button>
        ))}
      </div>
      <p className="px-3 pb-2 text-[10px] text-muted-foreground">
        {query ? `${results.length} matches` : `${active.label} · ${active.emojis.length} emojis`}
      </p>
    </div>
  );
}
